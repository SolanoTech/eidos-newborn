import { useEffect, type ReactNode } from "react";

/**
 * Модальное окно консоли в стилистике макета: стеклянная панель, заголовок с
 * подзаголовком и крестиком, тело и футер передаются детьми.
 */
export function Modal({
  title,
  subtitle,
  onClose,
  children,
  footer,
}: {
  title: string;
  subtitle?: string;
  onClose: () => void;
  children: ReactNode;
  footer?: ReactNode;
}) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
    };
    document.addEventListener("keydown", onKey);
    return () => document.removeEventListener("keydown", onKey);
  }, [onClose]);

  return (
    <div
      className="overlay"
      onClick={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
    >
      <div className="modal" role="dialog" aria-modal="true">
        <div className="modal-h">
          <div>
            <div className="mt">{title}</div>
            {subtitle && <div className="ms">{subtitle}</div>}
          </div>
          <button type="button" className="modal-x" onClick={onClose} aria-label="Закрыть">
            ✕
          </button>
        </div>
        <div className="modal-b">{children}</div>
        {footer && <div className="modal-f">{footer}</div>}
      </div>
    </div>
  );
}
