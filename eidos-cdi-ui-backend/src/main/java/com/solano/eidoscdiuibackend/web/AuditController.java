package com.solano.eidoscdiuibackend.web;

import com.solano.eidoscdiuibackend.service.AuditService;
import com.solano.eidoscdiuibackend.web.dto.AuditEventView;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

/** Чтение журнала аудита консоли (только ADMIN). */
@RestController
@RequestMapping("/api/v1/admin/audit")
@PreAuthorize("hasRole('ADMIN')")
public class AuditController {

    private final AuditService auditService;

    public AuditController(AuditService auditService) {
        this.auditService = auditService;
    }

    @GetMapping
    public List<AuditEventView> latest(@RequestParam(defaultValue = "100") int limit) {
        return auditService.latest(limit).stream().map(AuditEventView::of).toList();
    }
}
