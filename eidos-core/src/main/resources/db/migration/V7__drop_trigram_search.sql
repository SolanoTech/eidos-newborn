-- снятым слушателем она и её GIN-индекс превращаются в мёртвый вес на каждой
-- записи мерчанта.

DROP INDEX IF EXISTS ix_le_name_normalized_trgm;

ALTER TABLE legal_entity_record DROP COLUMN IF EXISTS name_normalized;

